"use client";

import { standardSchemaResolver } from "@hookform/resolvers/standard-schema";
import {
  OnboardingStepActions,
  OnboardingStepContainer,
  OnboardingStepForm,
  OnboardingStepHeader,
} from "@workspace/brand/onboarding";
import {
  type IdentityStepData,
  identityStepSchema,
} from "@workspace/brand/onboarding/lib/schemas";
import { FluriFieldV2Input } from "@workspace/forms/components/base/v2/fluri-field-v2-input";
import { FluriFieldV2Birthdate } from "@workspace/forms/components/specialized/v2/fluri-fields-v2";
import { getV2InputProps, useV2ControllerField } from "@workspace/forms/v2/rhf";
import { updateOnboardingStepAction } from "@workspace/supabase-data/actions/onboarding/flow-controller";
import { saveIdentityStepAction } from "@workspace/supabase-data/actions/onboarding/steps/identity-step-action";
import { useRouter } from "next/navigation";
import { useCallback, useEffect, useRef, useTransition } from "react";
import { Controller, useForm, useFormContext } from "react-hook-form";
import { toast } from "sonner";

interface IdentityPageClientProps {
  initialData: Partial<IdentityStepData>;
}

function DisplayNameField() {
  const { control } = useFormContext<IdentityStepData>();
  const { contract } = useV2ControllerField<IdentityStepData, "displayName">({
    control,
    name: "displayName",
    mode: "string",
  });

  return (
    <FluriFieldV2Input
      field={getV2InputProps(contract)}
      label="Nome de exibição"
      placeholder="Como você quer ser chamada(o)?"
      helperText="Este é o nome que aparecerá para seus pacientes na plataforma."
      required
      fullWidth
    />
  );
}

function BirthDateField() {
  const { control } = useFormContext<IdentityStepData>();
  const { contract } = useV2ControllerField<IdentityStepData, "birthDate">({
    control,
    name: "birthDate",
    mode: "string",
  });

  return (
    <FluriFieldV2Birthdate
      field={getV2InputProps(contract)}
      label="Data de nascimento"
      helperText="Use o formato DD/MM/AAAA."
      required
      fullWidth
    />
  );
}

export default function IdentityPageClient({ initialData }: IdentityPageClientProps) {
  const router = useRouter();
  const [isPending, startTransition] = useTransition();

  const methods = useForm<IdentityStepData>({
    resolver: standardSchemaResolver(identityStepSchema),
    defaultValues: {
      firstName: initialData.firstName ?? "",
      lastName: initialData.lastName ?? "",
      birthDate: initialData.birthDate ?? "",
      displayName: initialData.displayName ?? "",
    },
    mode: "onChange",
  });

  const {
    watch,
    setValue,
    control,
    formState: { isValid },
  } = methods;

  const autoSaveTimerRef = useRef<ReturnType<typeof setTimeout> | null>(null);

  const scheduleSave = useCallback(
    (values: Partial<IdentityStepData>) => {
      if (autoSaveTimerRef.current) clearTimeout(autoSaveTimerRef.current);

      autoSaveTimerRef.current = setTimeout(() => {
        startTransition(() => {
          void updateOnboardingStepAction({
            stepId: "identity",
            isComplete: false,
            draftData: values as Record<string, unknown>,
          });
        });
      }, 1500);
    },
    [startTransition],
  );

  useEffect(() => {
    const subscription = methods.watch((values) => {
      scheduleSave(values as Partial<IdentityStepData>);
    });

    return () => {
      subscription.unsubscribe();
      if (autoSaveTimerRef.current) clearTimeout(autoSaveTimerRef.current);
    };
  }, [methods, scheduleSave]);

  const firstName = watch("firstName");

  const updateDisplayName = (first: string) => {
    const currentDisplay = watch("displayName");
    const isAutoGenerated =
      !currentDisplay || currentDisplay === firstName || currentDisplay === first;

    if (isAutoGenerated && first) {
      setValue("displayName", first, { shouldValidate: false });
    }
  };

  const onSubmit = (data: IdentityStepData) => {
    startTransition(async () => {
      const normalizedFirstName = data.firstName.trim();
      const formData: IdentityStepData = {
        firstName: normalizedFirstName,
        lastName: data.lastName,
        birthDate: data.birthDate,
        displayName: data.displayName || normalizedFirstName,
      };

      const result = await saveIdentityStepAction(formData);

      if (result.success) {
        router.push("/onboarding/professional");
        return;
      }

      toast.error(result.error?.message || "Erro ao salvar dados. Tente novamente.");
    });
  };

  return (
    <OnboardingStepContainer>
      <OnboardingStepHeader
        title="Sobre você"
        description="Vamos começar com suas informações básicas. Esses dados aparecerão no seu perfil público."
      />

      <OnboardingStepForm methods={methods} onSubmit={onSubmit}>
        <div className="grid grid-cols-2 gap-3">
          <Controller
            control={control}
            name="firstName"
            render={({ field, fieldState }) => (
              <FluriFieldV2Input
                field={getV2InputProps({
                  value: field.value,
                  onValueChange: (value) => {
                    const nextValue = typeof value === "string" ? value : "";
                    field.onChange(nextValue);
                    updateDisplayName(nextValue);
                  },
                  onBlur: field.onBlur,
                  name: field.name,
                  ref: field.ref,
                  error: fieldState.error,
                })}
                label="Nome"
                placeholder="Ex: Ana"
                required
                fullWidth
              />
            )}
          />
          <Controller
            control={control}
            name="lastName"
            render={({ field, fieldState }) => (
              <FluriFieldV2Input
                field={getV2InputProps({
                  value: field.value,
                  onValueChange: (value) => {
                    field.onChange(typeof value === "string" ? value : "");
                  },
                  onBlur: field.onBlur,
                  name: field.name,
                  ref: field.ref,
                  error: fieldState.error,
                })}
                label="Sobrenome"
                placeholder="Ex: Silva"
                required
                fullWidth
              />
            )}
          />
        </div>

        <div className="grid grid-cols-2 gap-3">
          <DisplayNameField />
          <BirthDateField />
        </div>

        <OnboardingStepActions
          continueType="submit"
          continueLabel="Continuar"
          continuePendingLabel="Salvando..."
          isPending={isPending}
          continueDisabled={!isValid}
        />
      </OnboardingStepForm>
    </OnboardingStepContainer>
  );
}
